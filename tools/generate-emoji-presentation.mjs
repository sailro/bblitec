// Refresh the default-presentation data from the invoking Node/ICU version.
// This table is independent of installed font glyph coverage: the latter does
// not say whether Unicode asks for text or emoji presentation.
import { writeFileSync } from "node:fs";

const ranges = [];
let start = -1;
for (let point = 0; point <= 0x110000; point++) {
    const emoji = point < 0x110000 && /\p{Emoji_Presentation}/u.test(String.fromCodePoint(point));
    if (emoji && start < 0) start = point;
    if (!emoji && start >= 0) {
        ranges.push([start, point - 1]);
        start = -1;
    }
}
const hex = (value) => `0x${value.toString(16)}`;
const header = `// Generated by tools/generate-emoji-presentation.mjs.
// Node ${process.versions.node}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}.
#pragma once

#include <algorithm>
#include <array>
#include <utility>

namespace bbl::pal {

inline constexpr std::array<std::pair<char32_t, char32_t>, ${ranges.length}> ui_emoji_ranges{{
${ranges.map(([first, last]) => `    {${hex(first)}, ${hex(last)}},`).join("\n")}
}};

inline bool ui_default_emoji_presentation(char32_t point) {
    const auto range = std::lower_bound(
        ui_emoji_ranges.begin(), ui_emoji_ranges.end(), point,
        [](const auto& entry, char32_t value) { return entry.second < value; });
    return range != ui_emoji_ranges.end() && range->first <= point;
}

} // namespace bbl::pal
`;
writeFileSync(new URL("../native/src/pal_ui_emoji.hpp", import.meta.url), header);
