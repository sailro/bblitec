// Generates native/include/bblite/js_case.hpp: the Unicode case mappings
// JavaScript's String.prototype.toUpperCase / toLowerCase apply (full
// mappings: `ß` -> `SS`, `İ` -> `i̇`), and the Cased / Case_Ignorable code
// points the Final_Sigma rule reads, from the invoking Node/ICU version.
// Run from the repository root after a Node (ICU) upgrade:
// node tools/generate-case-tables.mjs
import { writeFileSync } from "node:fs";

/** @param {number} point */
const isSurrogate = (point) => point >= 0xd800 && point <= 0xdfff;

/**
 * One direction's mappings: single code points as runs (`first`..`last`
 * every `stride` points maps to point + `delta`), the rest as text.
 * @param {(text: string) => string} map
 */
function mappings(map) {
    /** @type {Array<[number, number]>} */
    const singles = [];
    /** @type {Array<[number, string]>} */
    const specials = [];
    for (let point = 0; point < 0x110000; point++) {
        if (isSurrogate(point)) continue;
        const text = String.fromCodePoint(point);
        const mapped = map(text);
        if (mapped === text) continue;
        const points = [...mapped];
        if (points.length === 1) singles.push([point, points[0].codePointAt(0)]);
        else specials.push([point, mapped]);
    }
    /** @type {Array<{first: number, last: number, delta: number, stride: number}>} */
    const runs = [];
    for (const [point, target] of singles) {
        const delta = target - point;
        const run = runs.at(-1);
        const stride = run && point - run.last;
        if (
            run &&
            run.delta === delta &&
            (stride === 1 || stride === 2) &&
            (run.first === run.last || run.stride === stride)
        ) {
            run.last = point;
            run.stride = stride;
        } else runs.push({ first: point, last: point, delta, stride: 1 });
    }
    return { runs, specials };
}

/** @param {RegExp} property */
function ranges(property) {
    /** @type {Array<[number, number]>} */
    const result = [];
    let start = -1;
    for (let point = 0; point <= 0x110000; point++) {
        const inside =
            point < 0x110000 &&
            !isSurrogate(point) &&
            property.test(String.fromCodePoint(point));
        if (inside && start < 0) start = point;
        if (!inside && start >= 0) {
            result.push([start, point - 1]);
            start = -1;
        }
    }
    return result;
}

const upper = mappings((text) => text.toUpperCase());
// A lone `Σ` lowercases to `σ`; the native Final_Sigma rule picks `ς`.
const lower = mappings((text) => text.toLowerCase());
const cased = ranges(/\p{Cased}/u);
const ignorable = ranges(/\p{Case_Ignorable}/u);

/** @param {number} value */
const hex = (value) => `0x${value.toString(16)}`;
/** @param {string} text */
const utf8 = (text) =>
    `"${[...Buffer.from(text, "utf8")].map((byte) => `\\x${byte.toString(16).padStart(2, "0")}`).join("")}"`;
const runTable = (name, runs) =>
    `inline constexpr std::array<CaseRun, ${runs.length}> ${name}{{\n${runs
        .map(
            (run) =>
                `    {${hex(run.first)}, ${hex(run.last)}, ${run.delta}, ${run.stride}},`,
        )
        .join("\n")}\n}};`;
const specialTable = (name, specials) =>
    `inline constexpr std::array<CaseSpecial, ${specials.length}> ${name}{{\n${specials
        .map(([point, text]) => `    {${hex(point)}, ${utf8(text)}},`)
        .join("\n")}\n}};`;
const rangeTable = (name, entries) =>
    `inline constexpr std::array<std::pair<char32_t, char32_t>, ${entries.length}> ${name}{{\n${entries
        .map(([first, last]) => `    {${hex(first)}, ${hex(last)}},`)
        .join("\n")}\n}};`;

const header = `// Generated by tools/generate-case-tables.mjs.
// Node ${process.versions.node}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}.
#pragma once

#include <algorithm>
#include <array>
#include <cstdint>
#include <string>
#include <utility>

namespace bbl::js::unicode_case {

/** \`first\`..\`last\`, every \`stride\` points, maps to the point plus \`delta\`. */
struct CaseRun {
    char32_t first;
    char32_t last;
    std::int32_t delta;
    std::uint8_t stride;
};

/** A point whose mapping is several points, as UTF-8. */
struct CaseSpecial {
    char32_t point;
    const char* text;
};

${runTable("upper_runs", upper.runs)}

${specialTable("upper_specials", upper.specials)}

${runTable("lower_runs", lower.runs)}

${specialTable("lower_specials", lower.specials)}

${rangeTable("cased_ranges", cased)}

${rangeTable("case_ignorable_ranges", ignorable)}

template <std::size_t Count>
[[nodiscard]] inline bool in_ranges(const std::array<std::pair<char32_t, char32_t>, Count>& table,
                                    char32_t point) {
    const auto range = std::lower_bound(
        table.begin(), table.end(), point,
        [](const auto& entry, char32_t value) { return entry.second < value; });
    return range != table.end() && range->first <= point;
}

/** The point's single-point mapping, or the point itself. */
template <std::size_t Count>
[[nodiscard]] inline char32_t mapped_point(const std::array<CaseRun, Count>& runs, char32_t point) {
    const auto run = std::lower_bound(
        runs.begin(), runs.end(), point,
        [](const CaseRun& entry, char32_t value) { return entry.last < value; });
    if (run == runs.end() || run->first > point || (point - run->first) % run->stride != 0)
        return point;
    return static_cast<char32_t>(static_cast<std::int32_t>(point) + run->delta);
}

/** The point's multi-point mapping as UTF-8, or null. */
template <std::size_t Count>
[[nodiscard]] inline const char* special_text(const std::array<CaseSpecial, Count>& specials,
                                              char32_t point) {
    const auto special = std::lower_bound(
        specials.begin(), specials.end(), point,
        [](const CaseSpecial& entry, char32_t value) { return entry.point < value; });
    return special != specials.end() && special->point == point ? special->text : nullptr;
}

/** Append a (non-surrogate) code point as UTF-8. */
inline void append_utf8(std::string& out, char32_t point) {
    if (point < 0x80) {
        out.push_back(static_cast<char>(point));
    } else if (point < 0x800) {
        out.push_back(static_cast<char>(0xc0 | (point >> 6)));
        out.push_back(static_cast<char>(0x80 | (point & 0x3f)));
    } else if (point < 0x10000) {
        out.push_back(static_cast<char>(0xe0 | (point >> 12)));
        out.push_back(static_cast<char>(0x80 | ((point >> 6) & 0x3f)));
        out.push_back(static_cast<char>(0x80 | (point & 0x3f)));
    } else {
        out.push_back(static_cast<char>(0xf0 | (point >> 18)));
        out.push_back(static_cast<char>(0x80 | ((point >> 12) & 0x3f)));
        out.push_back(static_cast<char>(0x80 | ((point >> 6) & 0x3f)));
        out.push_back(static_cast<char>(0x80 | (point & 0x3f)));
    }
}

} // namespace bbl::js::unicode_case
`;
writeFileSync(
    new URL("../native/include/bblite/js_case.hpp", import.meta.url),
    header,
);
console.log(
    `upper ${upper.runs.length} runs + ${upper.specials.length} specials, lower ${lower.runs.length} runs + ${lower.specials.length} specials, cased ${cased.length}, ignorable ${ignorable.length}`,
);
