// Generates native/src/pal_ui_search_cancel.hpp: Chromium's search field
// cancel button images (native/third_party/chromium, Chromium 152.0.7977.76
// third_party/blink/public/default_100_percent/blink; BSD-3-Clause notice:
// native/notices/Chromium.txt) as premultiplied RGBA rows, as Skia decodes
// them. Run from the repository root after replacing the images:
// node tools/generate-search-cancel.mjs. `--check` fails when the header is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { PNG } from "pngjs";

const images = [
    ["light", "search_cancel"],
    ["light_pressed", "search_cancel_pressed"],
    ["dark", "search_cancel_dark_mode"],
    ["dark_pressed", "search_cancel_pressed_dark_mode"],
];
const decoded = images.map(([name, file]) => {
    const png = PNG.sync.read(
        readFileSync(
            new URL(
                `../native/third_party/chromium/${file}.png`,
                import.meta.url,
            ),
        ),
    );
    /** @param {number} index */
    const byte = (index) => {
        const value = png.data[index];
        if (value === undefined) throw new Error(`${file}.png ends early.`);
        return value;
    };
    /** @type {number[]} */
    const bytes = [];
    for (let offset = 0; offset < png.data.length; offset += 4) {
        const alpha = byte(offset + 3);
        for (let channel = 0; channel < 3; channel++)
            bytes.push(Math.round((byte(offset + channel) * alpha) / 255));
        bytes.push(alpha);
    }
    return { name, file, width: png.width, height: png.height, bytes };
});
const first = decoded[0];
if (!first) throw new Error("No search cancel images to generate.");
const side = first.width;
for (const image of decoded)
    if (image.width !== side || image.height !== side)
        throw new Error(`${image.file}.png is not ${side}x${side}.`);
/** @param {number[]} bytes */
const rows = (bytes) => {
    const lines = [];
    for (let offset = 0; offset < bytes.length; offset += side * 4)
        lines.push(`    ${bytes.slice(offset, offset + side * 4).join(",")},`);
    return lines.join("\n");
};
const header = `// Generated by tools/generate-search-cancel.mjs from native/third_party/chromium.
// Chromium 152.0.7977.76 search field cancel button images; BSD-3-Clause
// notice: native/notices/Chromium.txt.
#pragma once

#include <array>
#include <cstdint>

namespace bbl::pal {

/** The images' side, in pixels. */
inline constexpr int ui_search_cancel_side = ${side};

using UiSearchCancelImage = std::array<std::uint8_t, ${side * side * 4}>;

// clang-format off
${decoded
    .map(
        (image) => `/** ${image.file}.png, premultiplied RGBA rows. */
inline constexpr UiSearchCancelImage ui_search_cancel_${image.name}{
${rows(image.bytes)}
};`,
    )
    .join("\n\n")}
// clang-format on

} // namespace bbl::pal
`;
const target = new URL(
    "../native/src/pal_ui_search_cancel.hpp",
    import.meta.url,
);
if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== header) {
        console.error(
            "native/src/pal_ui_search_cancel.hpp is stale: run node tools/generate-search-cancel.mjs.",
        );
        process.exitCode = 1;
    }
} else writeFileSync(target, header);
