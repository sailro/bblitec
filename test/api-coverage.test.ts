test("API project report keeps referenced declarations only and states readiness, unrouted functions and pin gaps", () => {
    const data = fixture(
        `export interface Options { used?: number; unused?: number }
        export declare function f(options: Options): void;
        export declare function h(): void;
        export declare function idle(): void;`,
        `import { f, h, g } from './index';
        const options = { used: 3 }; f(options); h(); g();`,
    );
    const usage = scanApiUsage(data.program, data, data.root);
    assert.deepEqual(usage.unresolved, ["g"]);
    const baseline = baselineOf(
        usage.uses.filter((use) => !use.id.startsWith("h:")),
    );
    const bindings = [
        {
            name: "f",
            owner: "f",
            status: "route-found" as const,
            lowerer: "compileFixture",
        },
        { name: "h", owner: "h", status: "no-route-observed" as const },
        { name: "idle", owner: "idle", status: "no-route-observed" as const },
    ];
    const report = apiCoverageReport(
        data.snapshot,
        usage,
        [],
        "",
        baseline,
        bindings,
        true,
    );
    assert.deepEqual(
        report.rows.map((row) => row.id.replace(/:[0-9a-f]{16}$/, "")).sort(),
        ["Options:interface.used:property", "f:function", "h:function"],
    );
    assert.deepEqual(report.metrics.surface, {
        covered: 2,
        total: 3,
        percent: 200 / 3,
    });
    assert.deepEqual(report.metrics.sites, {
        covered: 2,
        total: 3,
        percent: 200 / 3,
    });
    assert.equal(
        report.adapters.total,
        2,
        "the adapter census follows the referenced functions",
    );
    assert.ok(report.readiness);
    assert.equal(report.readiness.evidence, "current");
    assert.deepEqual(report.readiness.unrouted, ["h"]);
    assert.deepEqual(report.readiness.pinGap, ["g"]);
    assert.equal(
        apiCoverageReport(data.snapshot, usage, [], "", baseline, bindings)
            .readiness,
        undefined,
    );
    assert.equal(
        apiCoverageReport(
            data.snapshot,
            usage,
            [],
            "",
            undefined,
            bindings,
            true,
        ).readiness?.evidence,
        "stale",
    );
    const html = apiReportHtml(report);
    assert.ok(html.includes('"pinGap":["g"]'));
    assert.ok(!html.includes('"exports":'), "the page embeds no export table");
});
