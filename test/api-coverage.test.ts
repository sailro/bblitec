test("API collection includes dynamic test inputs, excludes refused and unreached calls, and preserves generated bytes", () => {
    const surface = loadApiSurface();
    const source = `import { createBoxData, createSphereData, invertMat4 } from '@babylonjs/lite';
        function unused() { createSphereData({ diameter: 7 }); }
        if (false) { invertMat4(new Float32Array(16)); }
        const box = createBoxData({ width: ${2 + 3} }); box.positions[0] = box.vertexCount;`;
    const silence = observeSourceTrace(() => {});
    let normal: ReturnType<typeof compileSource>;
    try {
        normal = compileSource(source);
    } finally {
        silence();
    }
    const uses: ReturnType<typeof scanApiUsage>["uses"] = [];
    let published = 0;
    const restore = observeSourceTrace((traces) => {
        published++;
        for (const trace of traces)
            uses.push(
                ...scanApiUsage(
                    trace.program,
                    surface,
                    process.cwd(),
                    trace.nodes,
                ).uses,
            );
    });
    try {
        assert.deepEqual(compileSource(source), normal);
        assert.throws(() =>
            compileSource(
                `import { createSphereData } from '@babylonjs/lite'; createSphereData({ unsupported: 7 });`,
            ),
        );
    } finally {
        restore();
    }
    assert.equal(published, 1);
    assert.ok(uses.some((use) => use.id.startsWith("createBoxData:function:")));
    assert.ok(
        uses.some((use) => use.id === "BoxOptions:interface.width:property"),
    );
    assert.ok(
        uses.some((use) => use.id === "BoxData:interface.vertexCount:property"),
    );
    assert.ok(
        !uses.some(
            (use) =>
                use.id.startsWith("createSphereData:") ||
                use.id.startsWith("invertMat4:"),
        ),
    );
});

test("API collection rolls back speculative lowering, failed replays and failed applications", () => {
    const data = fixture(
        "export declare function f(): void;",
        "const a = 1; const b = 2;",
    );
    const file = data.program.getSourceFile(join(data.root, "consumer.ts"))!;
    const [a, b] = file.statements;
    assert.ok(a && b);
    const collected: ts.Node[][] = [];
    const restore = observeSourceTrace((traces) => {
        for (const trace of traces) collected.push([...trace.nodes]);
    });
    try {
        traceSourceApplication(() => {
            assert.throws(() =>
                traceSourceProgram(data.program, () => {
                    traceSourceNode(b);
                    throw new Error("replay");
                }),
            );
            traceSourceProgram(data.program, () => {
                traceSourceNode(a);
                new EmissionTransaction().run(
                    () => {
                        traceSourceNode(b);
                        return false;
                    },
                    (result) => result,
                );
            });
        });
        assert.throws(() =>
            traceSourceApplication(() => {
                traceSourceProgram(data.program, () => traceSourceNode(b));
                throw new Error("worker failed");
            }),
        );
    } finally {
        restore();
    }
    assert.deepEqual(collected, [[a]]);
});

test("API collection resolves named option bags and metrics exclude type containers", () => {
    const data = fixture(
        `export interface Options { used?: number; unused?: number }
        export declare function f(options: Options): void;`,
        `import { f } from './index';
        const options = { used: 3 }; f(options);`,
    );
    const file = data.program.getSourceFile(join(data.root, "consumer.ts"))!;
    const reached = new Set<ts.Node>();
    const visit = (node: ts.Node): void => {
        reached.add(node);
        ts.forEachChild(node, visit);
    };
    visit(file);
    const usage = scanApiUsage(data.program, data, data.root, reached);
    assert.ok(
        usage.uses.some((use) => use.id === "Options:interface.used:property"),
    );
    const baseline = baselineOf(usage.uses);
    const report = apiCoverageReport(data.snapshot, usage, [], "", baseline);
    assert.equal(report.total, 4);
    assert.deepEqual(report.metrics.surface, {
        covered: 2,
        total: 3,
        percent: 200 / 3,
    });
    assert.equal(apiBaselineCurrent(baseline, "current", data.root), true);
    assert.equal(apiBaselineCurrent(baseline, "changed", data.root), false);
    assert.equal(
        apiCoverageReport(data.snapshot, usage, []).metrics.surface.covered,
        0,
    );
});

