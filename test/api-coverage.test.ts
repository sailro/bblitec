test("API evidence runner rejects skipped, todo, missing and failed tests", () => {
    const root = resolve("artifacts/api-evidence-unit");
    const path = join(root, "dist/test/probe.test.js");
    mkdirSync(join(root, "dist/test"), { recursive: true });
    writeFileSync(
        path,
        `import test from 'node:test';
        test('pass', () => {}); test.skip('skip', () => {}); test.todo('todo');
        test('fail', () => { throw new Error('expected failure'); });`,
    );
    const entry = (name: string): ApiCase => ({
        id: name,
        level: "generation",
        scope: "fixture",
        limitations: "fixture",
        test: { file: "test/probe.test.ts", name },
        targets: [{ id: "fixture", fingerprint: "fixture" }],
    });
    const runner = pathToFileURL(resolve("dist/src/api-evidence.js")).href;
    const execute = (names: string[]) => {
        const result = join(root, "receipt.json");
        const code = `import { runApiCases } from ${JSON.stringify(runner)};
            import { writeFileSync } from 'node:fs';
            writeFileSync(${JSON.stringify(result)}, JSON.stringify(await runApiCases(${JSON.stringify(root)},
                ${JSON.stringify(names.map(entry))}, 'inputs')));`;
        const env = { ...process.env };
        delete env.NODE_TEST_CONTEXT;
        const script = join(root, "run.mjs");
        writeFileSync(script, code);
        execFileSync(process.execPath, [script], { env, stdio: "pipe" });
        return readApiReceipt(result)!;
    };
    const receipt = execute(["pass", "skip", "todo", "missing"]);
    assert.deepEqual(
        receipt.cases.map((row) => row.status),
        ["passed", "skipped", "skipped", "missing"],
    );
    assert.equal(execute(["fail"]).cases[0]!.status, "failed");
});

