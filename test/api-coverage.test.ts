test("API body tracing follows original expressions through synthetic statements and records used adapters", () => {
    const file = ts.createSourceFile(
        "body.ts",
        "function original() { return Math.sqrt(4); }",
        ts.ScriptTarget.Latest,
        true,
    );
    const declaration = file.statements[0];
    assert.ok(declaration && ts.isFunctionDeclaration(declaration));
    const returned = declaration.body?.statements[0];
    assert.ok(
        returned && ts.isReturnStatement(returned) && returned.expression,
    );
    const traces: TranslationTrace[] = [];
    const restore = observePinnedTranslation((trace) => traces.push(trace));
    try {
        const output = lowerPinnedBody(
            file,
            [ts.factory.createReturnStatement(returned.expression)],
            {
                bindings: new Map(),
                calls: new Map([["unused", () => "unused()"]]),
                returnValue: (value, lowerer) => lowerer.expression(value!),
            },
        );
        assert.match(output, /std::sqrt\(4/);
    } finally {
        restore();
    }
    assert.equal(traces.length, 1);
    assert.equal(traces[0]?.symbolName, "original");
    assert.deepEqual(traces[0]?.requests, ["call: Math.sqrt"]);
});
function baselineOf(
    uses: ReturnType<typeof scanApiUsage>["uses"],
): ApiBaseline {
    return {
        schemaVersion: 2,
        inputs: "current",
        compilations: 1,
        testsPassed: 1,
        translations: [],
        suites: ["test/sample.test.ts"],
        files: [],
        uses: uses.map((use) => ({
            ...use,
            suite: "test/sample.test.ts",
            source: "source-hash",
        })),
    };
}

function fixture(declarations: string, consumer = "") {
    const root = resolve("artifacts/api-inventory-unit");
    const entry = join(root, "index.d.ts");
    const use = join(root, "consumer.ts");
    const sources = new Map([
        [entry, declarations],
        [use, consumer],
    ]);
    const options: ts.CompilerOptions = {
        strict: true,
        noLib: true,
        noEmit: true,
        target: ts.ScriptTarget.ES2022,
    };
    const host = ts.createCompilerHost(options, true);
    host.fileExists = (path) => sources.has(resolve(path));
    host.directoryExists = (path) => resolve(path).startsWith(root);
    host.readFile = (path) => sources.get(resolve(path));
    host.getSourceFile = (path, version) => {
        const text = sources.get(resolve(path));
        return text === undefined
            ? undefined
            : ts.createSourceFile(path, text, version, true);
    };
    const program = ts.createProgram([entry, use], options, host);
    const surface = extractApi(program, program.getSourceFile(entry)!, pin);
    return { ...surface, program, root };
}

