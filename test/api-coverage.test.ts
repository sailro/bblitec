test("API usage resolves overloads through imported aliases and separates option fields and read/write forms", () => {
    const data = fixture(
        `export interface Options { width?: number; depth?: number; }
        export interface Result { value: number; reset(x: number): void; reset(x: string): void; }
        export declare function create(x: number): Result;
        export declare function create(x: Options): Result;`,
        `
        import { create as alias } from './index';
        const saved = alias; const result = saved({ width: 3 });
        result.value += 1; result.reset('yes');
        const { value } = result;
        function neverCalled() { alias(5); }
    `,
    );
    const usage = scanApiUsage(data.program, data, data.root);
    assert.equal(
        usage.uses.filter(
            (use) => use.operation === "call" && use.id.startsWith("create:"),
        ).length,
        2,
    );
    const methodCalls = usage.uses.filter(
        (use) => use.operation === "call" && use.id.includes("reset"),
    );
    assert.equal(methodCalls.length, 1);
    assert.match(
        data.snapshot.items.find((item) => item.id === methodCalls[0]!.id)!
            .declaration,
        /string/,
    );
    assert.ok(
        usage.uses.some(
            (use) =>
                use.id.endsWith("width:property") &&
                use.operation === "provide",
        ),
    );
    assert.ok(!usage.uses.some((use) => use.id.endsWith("depth:property")));
    assert.ok(usage.uses.some((use) => use.operation === "read-write"));
    assert.ok(
        usage.uses.some(
            (use) =>
                use.operation === "read" && use.id.endsWith("value:property"),
        ),
    );
});

test("API observation never earns support, and evidence expires on source, case or declaration changes", () => {
    const data = fixture(
        `export declare function f(x: number): void;`,
        `import { f } from './index'; f(1);`,
    );
    const item = data.snapshot.items[0]!;
    const entry: ApiCase = {
        id: "f",
        level: "native",
        scope: "number 1",
        limitations: "other numbers untested",
        test: { file: "test/f.test.ts", name: "f" },
        targets: [{ id: item.id, fingerprint: item.fingerprint }],
    };
    const receipt = {
        schemaVersion: 1 as const,
        inputs: "current",
        cases: [
            {
                id: "f",
                definition: apiHash(JSON.stringify(entry)),
                status: "passed" as const,
            },
        ],
    };
    assert.equal(
        assessApiCases([entry], data.snapshot, receipt, "current")[0]!.status,
        "passed",
    );
    assert.equal(
        assessApiCases([entry], data.snapshot, receipt, "changed")[0]!.status,
        "stale",
    );
    assert.equal(
        assessApiCases(
            [{ ...entry, scope: "different" }],
            data.snapshot,
            receipt,
            "current",
        )[0]!.status,
        "stale",
    );
    assert.deepEqual(
        staleApiCases(
            [entry],
            fixture(`export declare function f(x: string): void;`).snapshot,
        ),
        ["f"],
    );
    const usage = scanApiUsage(data.program, data, data.root);
    assert.equal(
        apiCoverageReport(data.snapshot, usage, []).rows[0]!.status,
        "observed",
    );
    const assessed = assessApiCases([entry], data.snapshot, receipt, "current");
    assert.equal(
        apiCoverageReport(data.snapshot, usage, assessed).rows[0]!.status,
        "native-tested",
    );
    const refusal = {
        ...assessed[0]!,
        id: "refused-form",
        level: "refusal" as const,
    };
    assert.equal(
        apiCoverageReport(data.snapshot, usage, [...assessed, refusal]).rows[0]!
            .status,
        "partial",
    );
    assert.equal(
        apiCoverageReport(data.snapshot, usage, [refusal]).rows[0]!.status,
        "known-refusal",
    );
});

